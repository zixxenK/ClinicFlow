export function translate(message: string, language: AppLanguage) {
  if (language === 'en') return message
  const leading = message.match(/^\s*/)?.[0] ?? ''
  const trailing = message.match(/\s*$/)?.[0] ?? ''
  const key = message.trim()
  return leading + (french[key] ?? key) + trailing
}

export const LanguageContext = createContext<AppLanguage>('en')

export function useTranslate() {
  const language = useContext(LanguageContext)
  return useCallback((message: string) => translate(message, language), [language])
}

export function useLanguage() {
  return useContext(LanguageContext)
}
